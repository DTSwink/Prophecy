"""Compact studio layout: the audio canvas owns the workspace."""
from PySide6.QtCore import Qt
from PySide6.QtGui import QIcon
from PySide6.QtWidgets import (QWidget,QFrame,QLabel,QVBoxLayout,QHBoxLayout,QGridLayout,
    QSlider,QDoubleSpinBox,QLineEdit,QComboBox,QCheckBox,QSplitter,QDialog,QScrollArea,
    QProgressBar,QSizePolicy)
from audio_engine import HERE,Settings,DEFAULT_SOURCE,DEFAULT_TARGET,EQ_FREQUENCIES
from visual_audio import AudioDisplay,frequency_color


def build(w,state,source,target,label,button,panel,Control,FolderPane):
    root=QWidget();root.setObjectName('canvas');w.setCentralWidget(root)
    outer=QVBoxLayout(root);outer.setContentsMargins(14,10,14,8);outer.setSpacing(8)
    header=QHBoxLayout();header.setSpacing(10)
    icon=QLabel();icon.setPixmap(QIcon(str(HERE/'icon.ico')).pixmap(28,28));header.addWidget(icon)
    heading=label('Sound Studio');heading.setStyleSheet('font-size:18px;font-weight:650;color:#edf1fa;');header.addWidget(heading)
    header.addWidget(label(' /  PROPHECY','muted'));header.addStretch()
    w.live_badge=label('LIVE PREVIEW','section');header.addWidget(w.live_badge)
    w.folder_toggle=button('Folders',w.toggle_folders);header.addWidget(w.folder_toggle)
    header.addWidget(button('Guide',w.guide));outer.addLayout(header)
    w.split=QSplitter(Qt.Orientation.Horizontal);w.split.setChildrenCollapsible(False)
    w.source=FolderPane('SOURCE',source or state.get('source',str(DEFAULT_SOURCE)))
    w.target=FolderPane('SAVED MIXES',target or state.get('target',str(DEFAULT_TARGET)),True)
    for pane in (w.source,w.target):
        pane.setMinimumWidth(170);pane.setMaximumWidth(360)
        pane.list.setMinimumWidth(130)
        pane.list.setHorizontalScrollBarPolicy(Qt.ScrollBarPolicy.ScrollBarAlwaysOff)
        pane.list.setTextElideMode(Qt.TextElideMode.ElideMiddle)
        pane.chosen.connect(w.load);pane.directoryChanged.connect(w.save_preferences)
    w.split.addWidget(w.source)
    middle=QWidget();middle.setObjectName('canvas')
    main=QVBoxLayout(middle);main.setContentsMargins(0,0,0,0);main.setSpacing(6)
    # Single main surface; no stacked cards or hidden EQ tab.
    surface=QFrame();surface.setObjectName('surface')
    surface_layout=QVBoxLayout(surface);surface_layout.setContentsMargins(12,8,12,8);surface_layout.setSpacing(5)
    title_row=QHBoxLayout()
    w.clip_title=label('Choose a sound');w.clip_title.setObjectName('clipTitle')
    w.clip_title.setSizePolicy(QSizePolicy.Policy.Ignored,QSizePolicy.Policy.Preferred)
    title_row.addWidget(w.clip_title,1)
    w.metadata=label('WAV  /  LOCAL PROCESSING','muted');title_row.addWidget(w.metadata)
    w.reset_button=button('Reset',w.reset_controls);title_row.addWidget(w.reset_button)
    surface_layout.addLayout(title_row)
    eq_strip=QFrame();eq_strip.setObjectName('eqStrip');eq_row=QHBoxLayout(eq_strip)
    eq_row.setContentsMargins(2,6,2,7);eq_row.setSpacing(12)
    w.eq_sliders=[];w.eq_spins=[];w.eq_freqs=[];w.eq_widths=[];w.eq_labels=[]
    for index,freq in enumerate(EQ_FREQUENCIES):
        box=QWidget();column=QVBoxLayout(box);column.setContentsMargins(2,0,2,0);column.setSpacing(5)
        top=QHBoxLayout();top.setSpacing(4)
        band=label(str(index+1));band.setStyleSheet(f'color:{frequency_color(freq).name()};font-weight:700;');top.addWidget(band)
        frequency=QDoubleSpinBox();frequency.setRange(20,20000);frequency.setDecimals(0)
        frequency.setValue(freq);frequency.setSuffix(' Hz');frequency.setFixedWidth(85)
        frequency.setKeyboardTracking(False);top.addWidget(frequency)
        top.addStretch()
        gain=QDoubleSpinBox();gain.setRange(-12,12);gain.setSingleStep(.1);gain.setDecimals(1)
        gain.setSuffix(' dB');gain.setFixedWidth(70);gain.setKeyboardTracking(False);top.addWidget(gain)
        column.addLayout(top)
        slider=QSlider(Qt.Orientation.Horizontal);slider.setRange(-120,120);slider.setValue(0)
        slider.setStyleSheet(f'QSlider::sub-page:horizontal {{background:{frequency_color(freq).name()};}} QSlider::handle:horizontal {{background:{frequency_color(freq).name()};}}')
        slider.valueChanged.connect(lambda value,spin=gain:spin.setValue(value/10))
        gain.valueChanged.connect(lambda value,s=slider:s.setValue(round(value*10)))
        gain.valueChanged.connect(w.edited);frequency.valueChanged.connect(w.edited)
        slider.mouseDoubleClickEvent=lambda event,spin=gain:spin.setValue(0)
        column.addWidget(slider)
        width=QDoubleSpinBox();width.setRange(.2,8);width.setSingleStep(.1);width.setDecimals(2)
        width.setValue(.85);width.setPrefix('Q ');width.setFixedWidth(76);width.setKeyboardTracking(False)
        width.valueChanged.connect(w.edited)
        # Width is exposed in the details dialog; also editable with the mouse wheel over the graph.
        w.eq_widths.append(width)
        w.eq_freqs.append(frequency);w.eq_spins.append(gain);w.eq_sliders.append(slider);w.eq_labels.append(band)
        eq_row.addWidget(box,1)
    surface_layout.addWidget(eq_strip)
    graph_row=QHBoxLayout();graph_row.setContentsMargins(0,0,0,0);graph_row.setSpacing(4)
    w.wave=AudioDisplay();w.wave.trimChanged.connect(w.wave_trim);w.wave.seekRequested.connect(w.play_processed_at)
    w.wave.bandChanged.connect(w.graph_band_changed);graph_row.addWidget(w.wave,1)
    pitch_box=QWidget();pitch_box.setFixedWidth(66);pitch_layout=QVBoxLayout(pitch_box)
    pitch_layout.setContentsMargins(0,10,0,8);pitch_layout.setSpacing(6)
    title=label('PITCH','section');title.setAlignment(Qt.AlignmentFlag.AlignCenter);pitch_layout.addWidget(title)
    up=label('+12','muted');up.setAlignment(Qt.AlignmentFlag.AlignCenter);pitch_layout.addWidget(up)
    w.pitch=QSlider(Qt.Orientation.Vertical);w.pitch.setRange(-120,120);w.pitch.setValue(0)
    pitch_layout.addWidget(w.pitch,1,Qt.AlignmentFlag.AlignHCenter)
    down=label('−12','muted');down.setAlignment(Qt.AlignmentFlag.AlignCenter);pitch_layout.addWidget(down)
    w.pitch_spin=QDoubleSpinBox();w.pitch_spin.setRange(-12,12);w.pitch_spin.setDecimals(1)
    w.pitch_spin.setSingleStep(.1);w.pitch_spin.setKeyboardTracking(False);w.pitch_spin.setFixedWidth(66)
    w.pitch.valueChanged.connect(lambda value:w.pitch_spin.setValue(value/10))
    w.pitch_spin.valueChanged.connect(lambda value:w.pitch.setValue(round(value*10)));w.pitch_spin.valueChanged.connect(w.edited)
    w.pitch.mouseDoubleClickEvent=lambda event:w.pitch_spin.setValue(0)
    pitch_layout.addWidget(w.pitch_spin)
    semis=label('semitones','muted');semis.setAlignment(Qt.AlignmentFlag.AlignCenter);semis.setStyleSheet('font-size:10px;color:#7d90aa;')
    pitch_layout.addWidget(semis);graph_row.addWidget(pitch_box)
    surface_layout.addLayout(graph_row,1)
    transport=QHBoxLayout();transport.setSpacing(7)
    w.original_button=button('▶  Original',w.play_original)
    w.preview_button=button('▶  Processed',w.preview,'preview')
    w.stop_button=button('■',w.stop);w.stop_button.setFixedWidth(33)
    for b in (w.original_button,w.preview_button,w.stop_button):transport.addWidget(b)
    w.loop=QCheckBox('Loop');w.loop.toggled.connect(lambda x:setattr(w.player,'loop',x));transport.addWidget(w.loop)
    transport.addStretch()
    w.zoom=QComboBox();w.zoom.addItems(['Auto','1×','4×','16×']);w.zoom.setFixedWidth(69)
    w.zoom.setToolTip('Waveform magnification only. Auto is fixed from the original, so gain/peak changes stay visible.')
    w.zoom.currentTextChanged.connect(w.wave.set_zoom);transport.addWidget(label('View','muted'));transport.addWidget(w.zoom)
    transport.addWidget(label('Listen','muted'))
    w.monitor=QSlider(Qt.Orientation.Horizontal);w.monitor.setRange(0,100);w.monitor.setValue(50);w.monitor.setFixedWidth(70)
    w.monitor.valueChanged.connect(lambda v:setattr(w.player,'volume',v/100));transport.addWidget(w.monitor)
    surface_layout.addLayout(transport)
    w.preview_info=label('Change any control — the audio display updates automatically.','muted')
    w.preview_info.setMinimumHeight(16);surface_layout.addWidget(w.preview_info)
    main.addWidget(surface,1);w.wave_panel=surface
    # Compact always-present effects, freeing the canvas above.
    w.editor=QFrame();w.editor.setObjectName('strip');control_grid=QGridLayout(w.editor)
    control_grid.setContentsMargins(10,6,10,7);control_grid.setHorizontalSpacing(12)
    descriptors=[('fade_in_ms','Fade in',0,2000,5,1,' ms'),('fade_out_ms','Fade out',0,2000,5,1,' ms'),
                 ('speed','Speed',50,200,100,1,' %'),('reverb','Reverb',0,50,0,1,' %'),
                 ('polish','Polish',0,100,0,1,' %'),('gain_db','Gain',-24,18,0,.5,' dB')]
    for col,(key,*args) in enumerate(descriptors):
        control=Control(*args);control.spin.setFixedWidth(66)
        control.setStyleSheet('QLabel {font-size:11px;color:#a6b5cc;} QDoubleSpinBox {font-size:11px;padding:2px;}')
        control.changed.connect(w.edited);w.controls[key]=control;control_grid.addWidget(control,0,col)
    main.addWidget(w.editor)
    w.details=QDialog(w);w.details.setWindowTitle('Sound details');w.details.setMinimumWidth(650)
    details_layout=QVBoxLayout(w.details);details_layout.setSpacing(14)
    details_layout.addWidget(label('PRECISION & EXTRA EFFECTS','section'))
    details_grid=QGridLayout();details_grid.setHorizontalSpacing(22);details_grid.setVerticalSpacing(18)
    extra=[('start','Trim in',0,1,0,.001,' s'),('end','Trim out',0,1,1,.001,' s'),
           ('highpass','Low cut',0,500,0,1,' Hz'),('room','Reverb room size',0,100,35,1,' %'),
           ('denoise','Noise reduction',0,12,0,.5,' dB'),('noise_floor','Noise floor',-80,-20,-60,1,' dB')]
    for index,(key,*args) in enumerate(extra):
        control=Control(*args);control.changed.connect(w.edited);w.controls[key]=control
        details_grid.addWidget(control,index//2,index%2)
    details_layout.addLayout(details_grid)
    w.trim_info=label('','muted');details_layout.addWidget(w.trim_info)
    flags=QHBoxLayout();w.reverse=QCheckBox('Reverse');w.formants=QCheckBox('Preserve voice formants')
    w.reverse.toggled.connect(w.edited);w.formants.toggled.connect(w.edited)
    flags.addWidget(w.reverse);flags.addWidget(w.formants);flags.addStretch();details_layout.addLayout(flags)
    widths=QHBoxLayout();widths.addWidget(label('Band width:','muted'))
    for index,width in enumerate(w.eq_widths):widths.addWidget(label(str(index+1)));widths.addWidget(width)
    details_layout.addLayout(widths)
    details_layout.addWidget(label('Drag EQ points to choose a frequency. Mouse wheel changes Q (higher = narrower).','muted'))
    details_layout.addWidget(button('Done',w.details.hide))
    w.export_panel=QFrame();w.export_panel.setObjectName('strip');export=QVBoxLayout(w.export_panel)
    export.setContentsMargins(10,7,10,7);export.setSpacing(6)
    output=QHBoxLayout();output.setSpacing(6)
    w.output_name=QLineEdit();w.output_name.setPlaceholderText('Name your mix')
    output.addWidget(w.output_name,1)
    w.rate=QComboBox()
    for title,value in [('48 kHz',48000),('44.1 kHz',44100),('96 kHz',96000),('Source rate',0)]:w.rate.addItem(title,value)
    w.format=QComboBox()
    for title,value in [('16-bit WAV','PCM_16'),('24-bit WAV','PCM_24'),('32-bit float','FLOAT')]:w.format.addItem(title,value)
    w.channel_mode=QComboBox();w.channel_mode.addItems(['Keep source','Mono','Stereo'])
    for combo in (w.rate,w.format,w.channel_mode):combo.currentIndexChanged.connect(w.edited);output.addWidget(combo)
    w.generate_button=button('Generate  →',w.generate,'primary');output.addWidget(w.generate_button);export.addLayout(output)
    options=QHBoxLayout();options.setSpacing(9)
    w.protect=QCheckBox('Protect peaks');w.protect.setChecked(True)
    w.protect.setToolTip('Limit estimated true peak to −1 dBTP by reducing the whole clip only when necessary.')
    w.protect.toggled.connect(w.edited);options.addWidget(w.protect)
    w.normalize=QCheckBox('Peak normalize');w.normalize.toggled.connect(w.edited);options.addWidget(w.normalize)
    w.normalize_target=QDoubleSpinBox();w.normalize_target.setRange(-24,-1);w.normalize_target.setValue(-3)
    w.normalize_target.setSuffix(' dB');w.normalize_target.setDecimals(1);w.normalize_target.setSingleStep(.5)
    w.normalize_target.setFixedWidth(77);w.normalize_target.setKeyboardTracking(False)
    w.normalize_target.valueChanged.connect(w.edited);options.addWidget(w.normalize_target)
    options.addStretch();options.addWidget(button('Trim / extra effects',w.details.show));export.addLayout(options)
    main.addWidget(w.export_panel)
    w.split.addWidget(middle);w.split.addWidget(w.target);w.split.setStretchFactor(1,1);w.split.setSizes([190,1120,190])
    outer.addWidget(w.split,1)
    bottom=QHBoxLayout();w.status=label('Choose a WAV to begin.','muted');bottom.addWidget(w.status,1)
    w.cancel_button=button('Cancel',w.cancel_job);w.cancel_button.hide();bottom.addWidget(w.cancel_button);outer.addLayout(bottom)
    w.progress=QProgressBar();w.progress.setRange(0,0);w.progress.setTextVisible(False);w.progress.hide();outer.addWidget(w.progress)
