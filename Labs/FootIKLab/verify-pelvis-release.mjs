import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),K=require('./footik.js'),R=require('./recovery.js'),{load}=require('./test-bank.cjs');
const before=JSON.parse(fs.readFileSync(new URL('data/pelvis-release-before.json',import.meta.url))),run=load('walk',before.phase),model=K.prepare(run,before),checks=[];
const check=(name,ok)=>{assert(ok,name);checks.push(name);};
const foot=run.names.indexOf('foot_'+before.side),pelvis=run.names.indexOf('pelvis');
const forward=n=>{const p=model.sample(n/60).pose;return -R.rotate(R.qinv(p.q[pelvis]),R.sub(p.points[foot],p.points[pelvis]))[1];};
const rows=before.samples.map(s=>({...s,after:forward(s.frame)}));
const velocities=rows.slice(1).map((s,i)=>({frame:s.frame,before:(s.forward-rows[i].forward)*120,after:(s.after-rows[i].after)*120}));
check('Regression detects backward movement in pelvis space',velocities.some(s=>s.frame>=137&&s.before<-.2));
const recovery=velocities.filter(s=>s.frame>=139&&s.frame<=150);
check('Cleared foot keeps advancing relative to the moving, rotating pelvis',recovery.every(s=>s.after>.25));
const oldProgress=rows.find(s=>s.frame===147).forward-rows.find(s=>s.frame===137).forward;
const newProgress=forward(147)-forward(137);
check('137-147 pelvis-local progress substantially improves',newProgress>.10&&newProgress>oldProgress*2);
const middle=velocities.filter(s=>s.frame>=143&&s.frame<=147);
check('143-147 keeps advancing relative to the pelvis',Math.min(...middle.map(s=>s.after))>.4);
const result={passed:true,checks,measured:{beforeProgressCm:oldProgress*100,afterProgressCm:newProgress*100,minRecoverySpeed:Math.min(...recovery.map(s=>s.after)),clearanceRetreat137to138Cm:(forward(137)-forward(138))*100},velocities};
fs.writeFileSync(new URL('pelvis-release-verification.json',import.meta.url),JSON.stringify(result,null,2));
console.log(JSON.stringify({passed:result.passed,checks,measured:result.measured}));
