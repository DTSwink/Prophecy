"""Build the isolated, opt-in Jolt recovery profile and its Unreal test fixture.

Frozen native pelvismax weights; native-training spherical bounds with a 32 Hz
critically damped Jolt limit. No change to the installed Jolt DLL or PHAT assets.
"""
from pathlib import Path
import hashlib
import json
import shutil
import subprocess

ROOT = Path(__file__).resolve().parents[2]
BASE = ROOT / 'Saved/MimicKitTransfer/getup-transfer-20261023'
DEST = BASE / 'jolt-native-profile'


def main():
    DEST.mkdir(exist_ok=True)
    source = (BASE / 'fixture.cpp').read_text()
    limit = (ROOT / 'Labs/MimicKitTransfer/recovery_spherical_limit.inl').read_text()
    limit = limit.replace('float hz=std::getenv("CAND_LIMIT_HZ")?std::atof(std::getenv("CAND_LIMIT_HZ")):8.f;',
                          'constexpr float hz=32.f;')
    source = source.replace('class Layers final', limit + '\nclass Layers final', 1)
    source = source.replace('std::vector<Body*> bodies;',
                            'std::vector<Ref<TwoBodyConstraint>> extra;std::vector<Body*> bodies;')
    enabled = 'std::getenv("TRANSFER_NATIVE_BALL_LIMITS")&&j.actions[0]>=0&&j.actions[1]>=0&&j.actions[2]>=0'
    source = source.replace('else if(std::getenv("TRANSFER_NO_LIMITS"))',
                            'else if(std::getenv("TRANSFER_NO_LIMITS")||(' + enabled + '))')
    source = source.replace('physics.AddConstraint(joint);joints.push_back(joint);',
        'physics.AddConstraint(joint);joints.push_back(joint);\n'
        'if(' + enabled + '){Ref<TwoBodyConstraint> limit=new RecoverySphericalLimit('
        '*bodies[j.parent],*bodies[j.child],settings,j);physics.AddConstraint(limit);extra.push_back(limit);}')
    source = source.replace('~Fixture(){', '~Fixture(){for(auto& c:extra)physics.RemoveConstraint(c);')
    assert source.count('new RecoverySphericalLimit') == 1
    (DEST / 'fixture.cpp').write_text(source)
    shutil.copy2(BASE / 'jolt-rig-generated.h', DEST / 'jolt-rig-generated.h')
    build = (BASE / 'build.ps1').read_text().replace(str(BASE / 'fixture'), str(DEST / 'fixture'))
    (DEST / 'build.ps1').write_text(build)
    subprocess.run(['pwsh', '-NoProfile', '-File', str(DEST / 'build.ps1')], check=True)
    # Exactly the same physics class in the actual Unreal automation module.
    ue = source[:source.index('static int MotorSelfTest(')]
    ue = ue.replace('using namespace JPH;', 'namespace ProphecyRecoveryAudit {\nusing namespace JPH;', 1)
    ue = ue.replace('#include "jolt-rig-generated.h"', (DEST / 'jolt-rig-generated.h').read_text())
    (ROOT / 'Labs/MimicKitTransfer/generated/recovery_fixture.inl').write_text(
        '// Generated by build_getup_native_profile.py. Opt-in recovery world only.\n' + ue + '\n}\n')
    (DEST / 'profile.json').write_text(json.dumps(dict(
        profile='native-pelvismax-spherical32', activation='TRANSFER_NATIVE_BALL_LIMITS=1',
        physics_hz=240, policy_hz=30, velocity_iterations=40, position_iterations=8,
        limit_frequency_hz=32, limit_damping_ratio=1,
        floor_friction=1, floor_restitution=0, self_friction=0,
        original_gains_and_torque_caps=True, weights_changed=False,
        source_sha256=hashlib.sha256(source.encode()).hexdigest(),
        installed_dll_changed=False, gameplay_profile_changed=False), indent=2))


if __name__ == '__main__':
    main()
