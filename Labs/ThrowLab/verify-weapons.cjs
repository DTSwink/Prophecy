const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path'),crypto=require('node:crypto');
const C=require('./core.js'),S=require('./scenes.js'),{History}=require('./history.js');
const file=p=>path.resolve(__dirname,p),read=p=>JSON.parse(fs.readFileSync(file(p))),hash=p=>crypto.createHash('sha256').update(fs.readFileSync(file(p))).digest('hex');
const assets=read('data/objects.json'),geometry=read('../../Tools/BombFuse/Geometry.json'),whole=geometry.meshes[0];
assert.equal(assets.bomb.source.asset,geometry.source);
assert.equal(assets.bomb.source.sha256,hash('../../Tools/BombFuse/Geometry.json'));
assert.equal(assets.bomb.vertices.length,whole.vertices.length);
assert.deepEqual(assets.bomb.source.component.relativeScale3D,[2,2,2]);
assert.equal(assets.bomb.source.component.sha256,hash('../../Content/_mygame/bomb/A_Bomb.uasset'));
let bombError=0;
for(let i=0;i<whole.vertices.length;i++){
 const v=whole.vertices[i],expected=[(v[0]+1.0239047)*.02+.073,(v[2]+1.2153458)*.02+.078,v[1]*.02];
 for(let k=0;k<3;k++)bombError=Math.max(bombError,Math.abs(expected[k]-assets.bomb.vertices[i][k]));
}
assert(bombError<5.1e-9);
const shellWidth=Math.max(...assets.bomb.collision.map(v=>v[2]))-Math.min(...assets.bomb.collision.map(v=>v[2]));
assert(Math.abs(shellWidth-.224)<1e-7,'Bomb body must match the Blueprint\'s 22.4 cm diameter');
for(let i=0;i<whole.triangles.length;i+=3)assert.deepEqual(assets.bomb.triangles.slice(i,i+3),[whole.triangles[i],whole.triangles[i+2],whole.triangles[i+1]]);
assert.equal(assets.spear.source.sha256,hash('../../Exports/ImperialSpear/SM_ImperialSpear.fbx'));
assert.equal(assets.spear.vertices.length,assets.spear.source.vertexCount);
assert.equal(assets.spear.triangles.length/3,assets.spear.source.triangleCount);
const saved=read('fixtures/attack-presets.json').settings,legacy=structuredClone(saved);
legacy.clip='small-throw';legacy.object='sword';delete legacy.throwObjects;
let s=C.sanitize(legacy);
assert.equal(s.object,'bomb');assert.equal(C.sanitize({clip:'big-throw-2',object:'sword'}).object,'bomb');
const before=C.sanitize(saved);
for(const key of ['vanilla','grips','weaponScales','releases','imperialSpear'])assert.deepEqual(s[key],before[key]);
C.selectClip(s,'big-throw');assert.equal(s.object,'sword');
C.selectClip(s,'small-throw');assert.equal(s.object,'bomb');
const history=new History(s);C.selectObject(s,'sword');history.record(s);
s=C.sanitize(history.move());assert.equal(s.object,'bomb');
s=C.sanitize(history.move(true));assert.equal(s.object,'sword');
C.selectClip(s,'big-throw');assert.equal(s.object,'sword');C.selectObject(s,'bomb');
C.selectClip(s,'small-throw');assert.equal(s.object,'sword');
s=C.sanitize(JSON.parse(JSON.stringify(s)));assert.equal(s.object,'sword');
C.selectClip(s,'big-throw');assert.equal(s.object,'bomb');
const copied=S.pack(S.copy(S.open({settings:s}),'Copy','copy'));
assert.deepEqual(C.sanitize(copied.settings),s);
assert.equal(C.sanitize({clip:'big-throw',object:'bomb'}).object,'bomb');
const receipt={success:true,bombAsset:assets.bomb.source.asset,bombComponent:assets.bomb.source.component,bombBodyDiameterMetres:shellWidth,bombMaxVertexErrorMetres:bombError,spear:assets.spear.source,checks:'UE5 bomb geometry/topology and saved component scale; current spear FBX hash/counts; Small Throw migration/default; independent override, undo/redo, reload and copied scenes; preset tuning preserved.'};
fs.writeFileSync(file('../../Saved/ThrowLab/weapon-verification.json'),JSON.stringify(receipt,null,2));
