import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url),R=require('./recovery.js'),C=require('./core.js'),S=require('./support.js'),F=require('./flight.js');
const read=n=>JSON.parse(fs.readFileSync(new URL(n,import.meta.url),'utf8')),checks=[];
const check=(name,value)=>{assert(value,name);checks.push(name);};
const m=read('data/manifest.json'),run=F.decodeNN(read('data/roll-check.json')),jumps=['data/jumps.json','data/jumps-standing.json'].flatMap(n=>read(n).clips).map(F.decodeJump);
const pose=F.at(run,.5,m.parents),leg=S.leg(pose,run.names,'R'),normal=[0,0,-1];
const contact=R.add(pose.points[leg.foot],S.lowestOffset(pose,leg,normal)),wall=S.rectangle('wall',contact,[1,0,0],[0,1,0],[-2,2,-2,2]);
const settings=C.sanitize({...read('roll-settings.json'),loadMs:0,jumpFoot:'R',jumpSkew:.5});
const jump=F.create(run,jumps,settings,m.parents,pose,{time:0,surface:wall,poseAt:()=>pose,velocityAt:()=>[0,0,0],speed:0});
check('Real wall push succeeds',Number.isFinite(jump.jumpStart));
check('No arrow before push',jump.pushDebug(jump.jumpStart-1/60)===null);
for(let i=0;i<3;i++)check('Visible push frame '+i,!!jump.pushDebug(jump.jumpStart+i/60));
check('Hidden on fourth frame',jump.pushDebug(jump.jumpStart+3/60)===null);
const first=Math.ceil(jump.jumpStart*60-1e-7)/60;
check('Exactly three fixed playback ticks',Array.from({length:5},(_,i)=>jump.pushDebug(first+i/60)).filter(Boolean).length===3);
const push=jump.pushDebug(jump.jumpStart);
check('Uses skewed wall push direction',R.length(R.sub(push.direction,F.jumpDirection(normal,.5)))<1e-9&&Math.abs(push.direction[1]-Math.SQRT1_2)<1e-9);
check('Origin is on contact surface',Math.abs(R.dot(R.sub(push.origin,contact),normal))<1e-6);
jump.pushDebug(jump.jumpStart+10);
check('Backward seek reproduces arrow',JSON.stringify(jump.pushDebug(jump.jumpStart))===JSON.stringify(push));
const empty=F.sequence(run,jumps,{...settings,platforms:[],jumpEvents:[{id:'miss',time:.5,surface:'auto'}]},m.parents);
check('Missed jump produces no arrow',empty.pushDebug(.5)===null&&empty.pushDebug(1)===null);
check('Checkbox defaults off and persists',!C.sanitize().showJump&&C.sanitize(JSON.parse(JSON.stringify(C.sanitize({showJump:true})))).showJump);
const app=fs.readFileSync(new URL('app.js',import.meta.url),'utf8'),html=fs.readFileSync(new URL('index.html',import.meta.url),'utf8');
check('Checkbox appended after Cone',html.indexOf('id="showJump"')>html.indexOf('id="showCone"')&&html.indexOf('id="showJump"')<html.indexOf('Click: select'));
const block=app.slice(app.indexOf("  if(settings.showJump&&"),app.indexOf("  if(settings.animLeg&&"));
let triangles=[],shafts=[],draws=0;const depth=[];
const context={settings:{showJump:true,mode:'jump'},flight:jump,simTime:jump.jumpStart,normalize:R.unit,add:R.add,mul:R.mul,cross:R.cross,sub:R.sub,LabVertexStream:class {length=0;},gl:{DEPTH_TEST:1,TRIANGLES:4,disable:x=>depth.push(-x),enable:x=>depth.push(x)}};
const draw=vm.runInNewContext('(function(){'+block+'})',context),renderer={capsule:(...args)=>shafts.push(args),triangle:(...args)=>triangles.push(args),bindAndDraw:()=>draws++};
draw.call(renderer);
check('Draws large solid arrow',draws===1&&shafts.length===1&&triangles.length===24&&shafts[0][3]===.04);
check('Arrow tip is 1.4m along push',R.length(R.sub(triangles[0][1],R.add(push.origin,R.mul(push.direction,1.4))))<1e-9);
check('Arrow stays visible through body and restores depth',depth.join(',')==='-1,1');
context.settings.showJump=false;draw.call(renderer);
check('Disabled checkbox draws nothing',draws===1);
context.settings.showJump=true;context.simTime=jump.jumpStart+3/60;draw.call(renderer);
check('Expired arrow draws nothing',draws===1);
fs.writeFileSync(new URL('jump-arrow-verification.json',import.meta.url),JSON.stringify({passed:true,browserVisualVerified:false,checks},null,2));
console.log(JSON.stringify({passed:true,checks:checks.length,browserVisualVerified:false}));
