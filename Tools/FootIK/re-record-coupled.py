"""Independent current C + Torch oracle, with every request paired to its reply.

The old48 recorded-input solver fixtures are deliberately untouched. Those
prove the solver given fixed replies; they cannot prove that historic replies
still answer the root forecasts generated by today's complete causal system.
"""
import argparse, base64, gzip, hashlib, json, os, shutil, subprocess, sys, time
from pathlib import Path

PROJECT=Path(__file__).resolve().parents[2];LAB=PROJECT/'Labs/FootIKLab'
sys.dont_write_bytecode=True;sys.path.insert(0,str(LAB))
from nn_worker import ResumeLocomotion, inference_execution
from directional_nn import configure_direction
from surface_nn import Stream, source_version

DIRECTORY=PROJECT/'Saved/Diagnostics/FootIKPort20261030'
OUTPUT=DIRECTORY/'coupled-current'
def read(path):return json.loads(path.read_text(encoding='utf-8-sig'))
def digest(value):return hashlib.sha256(json.dumps(value,separators=(',',':'),allow_nan=False).encode()).hexdigest()
def canonical_frame(frame):
    out=dict(pose=dict(points=frame['pose']['points'],q=frame['pose']['q']),root=frame['root'])
    for key in ('feet','surface','slide','pelvisOffset','pelvisTransfer','influence','nn'):
        if key in frame:out[key]=frame[key]
    return out

@inference_execution()
def main(selected):
    node=shutil.which('node');version=subprocess.check_output([node,'-p',"process.version+' '+process.versions.v8"],text=True).strip()
    if version!='v24.19.0 13.6.233.17-node.51':raise RuntimeError('Pinned canonical Node required: '+version)
    OUTPUT.mkdir(parents=True,exist_ok=True);reports=[];owner=None;last_direction=None
    for name in selected:
        begin=time.perf_counter();original=read(DIRECTORY/(name+'.input.json'));settings=original['settings'];direction=settings.get('direction','forward')
        if owner is None or last_direction!=direction:
            owner=ResumeLocomotion('run');configure_direction(owner,'run',direction);owner.runtime.install_policy();last_direction=direction
        stream=Stream(owner);requests=[];replies=[];pairs=[]
        child=subprocess.Popen([node,str(LAB/'surface_driver.cjs')],cwd=LAB,stdin=subprocess.PIPE,stdout=subprocess.PIPE,stderr=subprocess.PIPE,text=True,encoding='utf-8',creationflags=subprocess.CREATE_NO_WINDOW if os.name=='nt' else 0)
        try:
            first=dict(source=original['source'],settings=settings,endTime=original.get('endTime',5),totalDuration=5)
            child.stdin.write(json.dumps(first,separators=(',',':'),allow_nan=False)+'\n');child.stdin.flush();done=None
            for line in child.stdout:
                message=json.loads(line)
                if 'error' in message:raise RuntimeError(message['error'])
                if message.get('done'):done=message;break
                request=message['step'];response=stream.step(request)
                requests.append(request);replies.append(response);pairs.append(dict(index=len(replies)-1,requestSha256=digest(request),responseSha256=digest(response)))
                child.stdin.write(json.dumps(response,separators=(',',':'),allow_nan=False)+'\n');child.stdin.flush()
            if done is None:raise RuntimeError('Canonical peer ended: '+child.stderr.read()[-2000:])
            child.stdin.close();child.wait(timeout=10)
            if child.returncode:raise RuntimeError('Canonical peer failed: '+child.stderr.read()[-2000:])
            if done['steps']!=replies:raise AssertionError('Peer replay table differs from the actual request/reply exchange')
            batch=done['frameBatch'];frames=json.loads(gzip.decompress(base64.b64decode(batch['data'])))
            if batch['start']!=0 or batch['count']!=len(frames):raise AssertionError('Incomplete canonical frame trace')
            diagnostics=done['diagnostics'];expected=dict(frames=list(map(canonical_frame,frames)),windows=diagnostics['coupling']['windows'],requests=requests,events=diagnostics.get('events',[]))
            inp=dict(original,policySteps=replies)
            (OUTPUT/(name+'.input.json')).write_text(json.dumps(inp,separators=(',',':'),allow_nan=False))
            (OUTPUT/(name+'.expected.json')).write_text(json.dumps(expected,separators=(',',':'),allow_nan=False))
            report=dict(name=name,frames=len(frames),policySteps=len(replies),sourceVersion=source_version(),node=version,seconds=time.perf_counter()-begin,policySeconds=stream.policy_seconds,originalInputSha256=hashlib.sha256((DIRECTORY/(name+'.input.json')).read_bytes()).hexdigest(),inputSha256=digest(inp),expectedSha256=digest(expected),pairedCalls=pairs)
            (OUTPUT/(name+'.receipt.json')).write_text(json.dumps(report,indent=2));reports.append({k:v for k,v in report.items() if k!='pairedCalls'})
            print(json.dumps(reports[-1]),flush=True)
        finally:
            if child.poll() is None:child.terminate();child.wait(timeout=10)
            for pipe in (child.stdin,child.stdout,child.stderr):
                if not pipe.closed:pipe.close()
    (OUTPUT/'manifest.json').write_text(json.dumps(dict(schema='footik-current-coupled-oracle-v1',basis='actual canonical C forecasts with canonical Torch Stream replies in one live causal run',cases=reports),indent=2))

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--case',action='append');a=p.parse_args();main(a.case or ['current-yaw-stop10','coupled-wall-walk','coupled-wall-run'])
