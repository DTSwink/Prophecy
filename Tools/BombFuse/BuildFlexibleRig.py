"""Blender background: original geometry, fixed shell, five cosmetic fuse joints."""
import bpy,json,pathlib,math
from mathutils import Vector
root=pathlib.Path(__file__).resolve().parents[2]
out=root/'Saved/Diagnostics/BombFuseFlexible';out.mkdir(parents=True,exist_ok=True)
source=json.loads((root/'Saved/Diagnostics/BombFuse/mesh.json').read_text())
v=source['vertices'];tris=[source['triangles'][i:i+3] for i in range(0,len(source['triangles']),3)]
def bl(p):return (p[0],-p[1],p[2])
rings=[sum((Vector(v[76+s*60+2*r+j]) for s in range(8) for j in range(2)),Vector())/16 for r in range(30)]
centers=rings[1:];arc=[0.]
for a,b in zip(centers,centers[1:]):arc.append(arc[-1]+(b-a).length)
length=arc[-1]
def point(d):
 for i in range(len(arc)-1):
  if d<=arc[i+1]:return centers[i].lerp(centers[i+1],(d-arc[i])/(arc[i+1]-arc[i]))
 return centers[-1]
knots=[point(length*i/5) for i in range(6)]
bpy.ops.wm.read_factory_settings(use_empty=True)
mesh=bpy.data.meshes.new('SK_BombFuse');mesh.from_pydata([bl(p) for p in v],[],[list(reversed(t)) for t in tris]);mesh.update()
mesh.materials.append(bpy.data.materials.new('BombBody'));mesh.materials.append(bpy.data.materials.new('Fuse'))
uv=mesh.uv_layers.new(name='UV0');burn=mesh.uv_layers.new(name='UV1')
progress=[0.]*len(v)
for s in range(8):
 for r in range(30):
  for j in range(2):progress[76+s*60+2*r+j]=.01+.99*arc[max(0,r-1)]/length
for i in range(556,564):progress[i]=1.
for p in mesh.polygons:
 p.use_smooth=True;p.material_index=1 if 76<=p.vertices[0]<564 else 0
 for li in p.loop_indices:
  i=mesh.loops[li].vertex_index;u,w=source['uv'][i];uv.data[li].uv=(u,1-w);burn.data[li].uv=(progress[i],1)
mesh.normals_split_custom_set([bl(source['normals'][loop.vertex_index]) for loop in mesh.loops])
obj=bpy.data.objects.new('SK_BombFuse',mesh);bpy.context.collection.objects.link(obj)
armdata=bpy.data.armatures.new('BombFuseRig');arm=bpy.data.objects.new('Armature',armdata);bpy.context.collection.objects.link(arm)
arm.select_set(True);bpy.context.view_layer.objects.active=arm;bpy.ops.object.mode_set(mode='EDIT')
rb=armdata.edit_bones.new('strap_root');rb.head=(0,0,0);rb.tail=(0,0,1);last=rb
for i in range(5):
 b=armdata.edit_bones.new(f'strap_{i+1:02d}');b.head=bl(knots[i]);b.tail=bl(knots[i+1]);b.parent=last;b.use_connect=i>0;last=b
b=armdata.edit_bones.new('strap_tip');b.head=bl(knots[-1]);b.tail=Vector(bl(knots[-1]))+(Vector(bl(knots[-1]))-Vector(bl(knots[-2]))).normalized()*.2;b.parent=last;b.use_connect=True
bpy.ops.object.mode_set(mode='OBJECT')
names=['strap_root']+[f'strap_{i+1:02d}' for i in range(5)]+['strap_tip']
groups=[obj.vertex_groups.new(name=n) for n in names]
weights=[]
for i in range(len(v)):
 if not 76<=i<564:ws=[(0,1.)]
 else:
  # Blend across each joint, but rigidly anchor the embedded first ring.
  u=max(0.,min(5.,(progress[i]-.01)/.99*5));j=min(4,int(u));t=u-j
  ws=[(j,1-t),(j+1,t)]
 for j,w in ws:
  if w>0:groups[j].add([i],w,'REPLACE')
 weights.append(ws)
mod=obj.modifiers.new('Fuse skinning','ARMATURE');mod.object=arm;obj.parent=arm
bpy.context.scene.unit_settings.system='METRIC';bpy.context.scene.unit_settings.scale_length=.01
bpy.ops.object.select_all(action='DESELECT');obj.select_set(True);arm.select_set(True);bpy.context.view_layer.objects.active=arm
bpy.ops.export_scene.fbx(filepath=str(out/'SK_BombFuse.fbx'),use_selection=True,object_types={'MESH','ARMATURE'},use_mesh_modifiers=False,add_leaf_bones=False,bake_anim=False,mesh_smooth_type='OFF',axis_forward='-Y',axis_up='Z',primary_bone_axis='Y',secondary_bone_axis='X',apply_unit_scale=True)
report={'length_cm':length,'centers':[list(x) for x in centers],'arc':arc,'knots':[list(x) for x in knots],'weights':weights,'vertices':len(v),'triangles':len(tris)}
(out/'rig.json').write_text(json.dumps(report))
header='#pragma once\n// Generated by Tools/BombFuse/BuildFlexibleRig.py.\n'
header+='static const FVector BombFuseCenters[] = {\n'+''.join('FVector(%.9f,%.9f,%.9f),\n'%tuple(p) for p in centers)+'};\n'
header+='static constexpr double BombFuseArc[] = {'+','.join('%.9f'%x for x in arc)+'};\n'
(root/'Source/GameAnimationSample3/Private/ProphecyBombFuseCurve.h').write_text(header)
print('FLEXIBLE BOMB',len(v),len(tris),length)
