"""Bake the inspected CC0 bomb's curved fuse coordinates and 20 closed shell pieces.
Reads a read-only Unreal LOD0 export; never modifies the imported mesh.
"""
import json, pathlib, math
import numpy as np
root=pathlib.Path(__file__).resolve().parents[2]
m=json.loads((root/'Saved/Diagnostics/BombFuse/mesh.json').read_text())
v=np.asarray(m['vertices']); tri=np.asarray(m['triangles']).reshape(-1,3)
# This source has eight UV strips of 30 rings, followed by its tip cap.
assert len(v)==1799 and len(tri)==2622
fuse=set(range(76,564))
assert all(all(int(i) in fuse for i in t) or all(int(i) not in fuse for i in t) for t in tri)
rings=[]
for ring in range(30):
 ids=[]
 for strip in range(8):
  k=76+strip*60
  ids.extend([k,k+1] if ring==0 else [k+2*ring,k+2*ring+1])
 rings.append(v[ids].mean(axis=0))
arc=np.r_[0,np.cumsum(np.linalg.norm(np.diff(rings[1:],axis=0),axis=1))]
length=float(arc[-1]); progress=np.zeros(len(v))
for strip in range(8):
 for ring in range(30):
  value=.01+.99*(arc[max(0,ring-1)]/length)
  progress[76+strip*60+2*ring:76+strip*60+2*ring+2]=value
progress[556:564]=1
def row(i):return [*v[i],*m['normals'][i],*m['uv'][i],*m['tangents'][i][:3],-1 if m['tangents'][i][3] else 1,float(progress[i])]
meshes=[{'name':'SM_BombBurn','vertices':[row(i) for i in range(len(v))],'triangles':m['triangles'],'whole':True}]
shell=np.array([t for t in tri if int(t[0]) not in fuse]); center=np.array([-1.0239047,0,-1.2153458])
dirs=v[shell].mean(axis=1)-center;dirs/=np.linalg.norm(dirs,axis=1)[:,None]
# Farthest point spherical seeds followed by a few offline Lloyd iterations.
seeds=[dirs[np.argmax(dirs[:,2])]]
for k in range(19):seeds.append(dirs[np.argmin(np.max(dirs@np.array(seeds).T,axis=1))])
seeds=np.array(seeds)
for _ in range(12):
 labels=np.argmax(dirs@seeds.T,axis=1)
 seeds=np.array([dirs[labels==i].mean(axis=0) for i in range(20)]);seeds/=np.linalg.norm(seeds,axis=1)[:,None]
for part in range(20):
 ts=shell[labels==part]; ids=sorted(set(ts.flat)); ix={i:j for j,i in enumerate(ids)}
 rows=[row(i) for i in ids]; n=len(rows)
 for i in ids:
  d=v[i]-center;d/=np.linalg.norm(d);r=row(i);r[:3]=list(v[i]-.22*d);r[3:6]=list(-np.array(r[3:6]));rows.append(r)
 triangles=[];edges={}
 def key(i):return tuple(np.round(v[i],4))
 for a,b,c in ts:
  triangles.extend([ix[a],ix[b],ix[c],ix[c]+n,ix[b]+n,ix[a]+n])
  for x,y in [(a,b),(b,c),(c,a)]:edges.setdefault(tuple(sorted([key(x),key(y)])),[]).append((x,y))
 for es in edges.values():
  if len(es)==1:
   a,b=es[0];a=ix[a];b=ix[b];triangles.extend([a,b+n,b,a,a+n,b+n])
 assert len(ts)>0
 meshes.append({'name':f'SM_BombFragment_{part:02}','vertices':rows,'triangles':triangles,'whole':False})
output={'source':'/Game/Fab/CC0_-_Bomb/cc0_bomb/StaticMeshes/cc0_bomb.cc0_bomb','fuse_length_cm':length,'meshes':meshes}
(root/'Tools/BombFuse/Geometry.json').write_text(json.dumps(output,separators=(',',':')))
header='#pragma once\n// Generated by Tools/BombFuse/PrepareGeometry.py from the original curved fuse.\n'
header+='static const FVector BombFuseSegments[] = {\n'+''.join('    FVector(%.9f,%.9f,%.9f),\n'%tuple(d) for d in np.diff(rings[1:],axis=0))+'};\n'
(root/'Source/GameAnimationSample3/Private/ProphecyBombGeometry.h').write_text(header)
print('Fuse length cm:',length,'Meshes:',len(meshes),'Triangles:',[len(x['triangles'])//3 for x in meshes])
