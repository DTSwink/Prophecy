"""Freeze the accepted double-reach math for an isolated editor benchmark.

No production code is edited. Regenerate before every comparison; the generated
header carries the source SHA256 so measurements cannot silently use old math.
"""
from pathlib import Path
import hashlib
p=Path(__file__).resolve().parents[2]
src=p/'Source/GameAnimationSample3/Private/ProphecyDoubleReachAnimInstance.cpp'
text=src.read_text()
kernel=text[text.index('namespace ProphecyDoubleReach\n'):text.index('FCompactPoseBoneIndex ResolveCompactBoneIndex')]
kernel=kernel.replace('namespace ProphecyDoubleReach','namespace ProphecyReachBenchmarkKernel',1)+'}\n'
sha=hashlib.sha256(src.read_bytes()).hexdigest()
out=p/'Source/ProphecyEditor/Private/Benchmarks/DoubleReachKernel.inl'
out.parent.mkdir(parents=True,exist_ok=True)
out.write_text('// Generated by Tools/Benchmarks/PrepareDoubleReachBenchmark.py\n'
    '// Production source SHA256: '+sha+'\n'+kernel)
print(sha)
