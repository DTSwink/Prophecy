"""Run through RunUnrealRemote.py. Bake idle parent-local offsets from frame 0; no asset writes."""
import unreal, pathlib, json, hashlib, math
root=pathlib.Path(unreal.Paths.project_dir())
path='/Game/Characters/UEFN_Mannequin/Animations/Idle/M_Neutral_Stand_Idle_Loop'
clip=unreal.load_asset(path)
names=['pelvis','spine_01','spine_02','spine_03','spine_04','spine_05','clavicle_l','upperarm_l','lowerarm_l','hand_l','clavicle_r','upperarm_r','lowerarm_r','hand_r','neck_01','neck_02','head']
parents=[-1,0,1,2,3,4,5,6,7,8,5,10,11,12,5,14,15]
rate=60; ticks=round(clip.get_play_length()*rate); subdivisions=10
assert abs(ticks/rate-clip.get_play_length())<1.e-6
raw=[];deltas=[]
for tick in range(ticks*subdivisions+1):
 pose=unreal.AnimationLibrary.get_bone_poses_for_time(clip,names,tick/(rate*subdivisions),False)
 raw.append([[t.translation.x,t.translation.y,t.translation.z,t.rotation.x,t.rotation.y,t.rotation.z,t.rotation.w] for t in pose])
 if tick==0:base=pose
 frame=[]
 for t,b in zip(pose,base):
  p=t.translation-b.translation;r=b.rotation;q=t.rotation*unreal.Quat(-r.x,-r.y,-r.z,r.w)
  if q.w<0:q=unreal.Quat(-q.x,-q.y,-q.z,-q.w)
  norm=math.sqrt(q.x*q.x+q.y*q.y+q.z*q.z+q.w*q.w)
  frame.append([p.x,p.y,p.z,q.x/norm,q.y/norm,q.z/norm,q.w/norm] if tick else [0,0,0,0,0,0,1])
 deltas.append(frame)
legs=['thigh_l','calf_l','foot_l','ball_l','thigh_r','calf_r','foot_r','ball_r']
legpose=unreal.AnimationLibrary.get_bone_poses_for_time(clip,legs,0,False)
fixture=dict(source=path,rate=rate,ticks=ticks,names=names,parents=parents,raw=raw[::subdivisions],deltas=deltas[::subdivisions],legs=legs,leg_local=[[t.translation.x,t.translation.y,t.translation.z,t.rotation.x,t.rotation.y,t.rotation.z,t.rotation.w] for t in legpose])
out=root/'Saved/Diagnostics/Breathing20261014';out.mkdir(parents=True,exist_ok=True)
(out/'idle.json').write_text(json.dumps(fixture,separators=(',',':')),encoding='utf-8')
def f(x):
 s=format(float(x),'.9g')
 return s+('f' if '.' in s or 'e' in s else '.f')
asset=root/'Content/Characters/UEFN_Mannequin/Animations/Idle/M_Neutral_Stand_Idle_Loop.uasset'
text='#pragma once\n// Generated by Tools/NN/ExportBreathing.py from '+path+'\n// Asset SHA256 '+hashlib.sha256(asset.read_bytes()).hexdigest()+'\n// Parent-local translation difference and Q(t)*inverse(Q(0)).\n// One shared tenth-tick grid pre-bakes every 0.3..1.0 speed; no runtime resampling.\nnamespace ProphecyBreathingData\n{\n'
text+='inline constexpr int Count=17, Ticks='+str(ticks)+', Phases=Ticks*10;\n'
text+='inline constexpr const TCHAR* Names[Count]={'+','.join('TEXT("'+n+'")' for n in names)+'};\n'
text+='inline constexpr int Parents[Count]={'+','.join(map(str,parents))+'};\n'
text+='inline constexpr float Samples[Phases+1][Count][7]={\n'
text+='\n'.join('{'+','.join('{'+','.join(map(f,v))+'}' for v in frame)+'},' for frame in deltas)
text+='\n};\n}\n'
(root/'Source/GameAnimationSample3/Private/ProphecyBreathingData.h').write_text(text,encoding='utf-8')
print('BREATHING_EXPORTED',ticks,len(text))
out=root/'Saved/Diagnostics/BreathingSpeed20261014';out.mkdir(parents=True,exist_ok=True)
(out/'idle-fine.json').write_text(json.dumps(dict(source=path,rate=rate*subdivisions,raw=raw),separators=(',',':')),encoding='utf-8')
